# Input: String 'Pemrograman'
teks = "Pemrograman"

# Proses: Mengakses karakter tertentu menggunakan indeks ([0], [-1]) dan melakukan slicing ([:4], [4:], [::-1])

# Output: Menampilkan karakter pertama, karakter terakhir, 4 karakter awal, karakter dari indeks 4 hingga akhir, dan string terbalik
print(teks[0])
print(teks[-1])
print(teks[:4])
print(teks[4:])
print(teks[::-1])